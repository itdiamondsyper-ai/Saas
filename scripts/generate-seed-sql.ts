/**
 * Generates supabase/seed.sql from the same seed builder the demo mode uses.
 * Timestamps are written relative to now() so the data looks current whenever
 * the seed is applied. Run with: npm run db:seed:generate
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { buildSeed } from "../lib/demo/seed";

const now = new Date();
const seed = buildSeed(now);
const DATE_COLUMNS = new Set(["start_date", "due_date", "issue_date", "incurred_on"]);
const TIMESTAMP_COLUMNS = /(_at|_end)$/;

const quote = (value: string) => `'${value.replace(/'/g, "''")}'`;

function sqlValue(column: string, value: unknown): string {
  if (value === null || value === undefined) return "null";
  if (Array.isArray(value)) return value.length ? `array[${value.map((v) => quote(String(v))).join(", ")}]::text[]` : "'{}'::text[]";
  if (typeof value === "object") return `${quote(JSON.stringify(value))}::jsonb`;
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  const str = String(value);
  if (DATE_COLUMNS.has(column) && /^\d{4}-\d{2}-\d{2}$/.test(str)) {
    const days = Math.round((Date.parse(`${str}T00:00:00Z`) - Date.parse(`${now.toISOString().slice(0, 10)}T00:00:00Z`)) / 86_400_000);
    return `(current_date + ${days})`;
  }
  if (TIMESTAMP_COLUMNS.test(column) && !Number.isNaN(Date.parse(str))) {
    const seconds = Math.round((Date.parse(str) - now.getTime()) / 1000);
    return `(now() + interval '${seconds} seconds')`;
  }
  return quote(str);
}

function insert(table: string, rows: Record<string, unknown>[], conflict = "") {
  if (!rows.length) return "";
  const columns = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${columns.map((c) => sqlValue(c, r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values}${conflict ? `\n${conflict}` : ""};\n\n`;
}

const profiles = seed.tables.profiles;
let sql = `-- FlowPilot demo seed (generated by scripts/generate-seed-sql.ts — do not edit by hand).
-- Creates the "Vertex Creative" workspace with four users. Password for every user: ${seed.users[0].password}
-- Apply with \`supabase db reset\` locally, or paste into the SQL editor of a development project.

begin;

`;

for (const user of seed.users) {
  const profile = profiles.find((p) => p.id === user.id)!;
  sql += `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change, email_change_token_new, recovery_token)
values ('00000000-0000-0000-0000-000000000000', ${quote(user.id)}, 'authenticated', 'authenticated', ${quote(user.email)}, extensions.crypt(${quote(user.password)}, extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}'::jsonb, ${quote(JSON.stringify({ full_name: profile.full_name }))}::jsonb, now(), now(), '', '', '', '')
on conflict (id) do nothing;
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${quote(user.id)}, ${quote(user.id)}, ${quote(JSON.stringify({ sub: user.id, email: user.email, email_verified: true }))}::jsonb, 'email', now(), now(), now())
on conflict do nothing;

`;
}

const t = seed.tables;
sql += insert(
  "profiles",
  profiles as unknown as Record<string, unknown>[],
  "on conflict (id) do update set full_name = excluded.full_name, job_title = excluded.job_title, notification_prefs = excluded.notification_prefs, last_active_at = excluded.last_active_at",
);
const ordered: (keyof typeof t)[] = [
  "workspaces", "workspace_members", "workspace_invitations", "subscriptions", "billing_history", "clients", "projects",
  "project_members", "tasks", "task_comments", "invoices", "invoice_items", "expenses", "notifications", "activity_logs",
];
for (const table of ordered) sql += insert(table, t[table] as unknown as Record<string, unknown>[], "on conflict do nothing");
sql += "commit;\n";

const target = path.join(__dirname, "..", "supabase", "seed.sql");
writeFileSync(target, sql);
console.log(`Wrote ${target} (${(sql.length / 1024).toFixed(0)} KB)`);
